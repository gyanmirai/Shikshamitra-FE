import fs from 'node:fs/promises';
import { chromium } from '@playwright/test';
const out=new URL('../../../.artifacts/work-shifts/',import.meta.url);await fs.mkdir(out,{recursive:true});
const shiftName='Independent Office Shift '+Date.now();
const browser=await chromium.launch({headless:true});const page=await browser.newPage({viewport:{width:1366,height:900}});
try {
 await page.goto('http://127.0.0.1:4321/');
 await page.getByRole('button',{name:'Employee shifts',exact:true}).click();
 await page.getByRole('heading',{name:'Work Shifts',exact:true}).waitFor();
 await page.getByRole('button',{name:'Create work shift',exact:true}).first().click();
 const dialog=page.getByRole('dialog');await dialog.getByLabel('Shift Name').fill(shiftName);
 await dialog.getByRole('button',{name:'Submit',exact:true}).click();
 await page.getByText(shiftName,{exact:true}).waitFor();
 await page.screenshot({path:new URL('hr-catalogue.png',out).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
 await page.getByRole('button',{name:'Edit '+shiftName,exact:true}).click();
 await page.getByRole('dialog').getByLabel('Shift Name').fill('Unsaved draft');
 await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
 await page.getByRole('dialog',{name:'Discard Changes'}).waitFor();
 await page.getByRole('button',{name:'Keep editing',exact:true}).click();
 if(await page.getByRole('dialog').getByLabel('Shift Name').inputValue() !== 'Unsaved draft') throw new Error('Discard guard lost draft');
 await page.getByRole('dialog').getByRole('button',{name:'close',exact:true}).click();
 await page.getByRole('button',{name:'Discard changes',exact:true}).click();
 await page.getByText(shiftName,{exact:true}).waitFor();
 await page.getByRole('button',{name:'School shifts',exact:true}).click();
 if(await page.getByText(shiftName,{exact:true}).count()) throw new Error('HR shift leaked into school catalogue');
 const fixture=await (await page.request.get('http://127.0.0.1:4391/fixture/context')).json();
 const headers={Authorization:'Bearer aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa'};
 const shifts=await(await page.request.get('http://127.0.0.1:4391/api/hr/work-shifts',{headers})).json();
 const scheduleUrl='http://127.0.0.1:4391/api/hr/employees/'+fixture.employeeId+'/shift-assignments';
 let schedule=await(await page.request.get(scheduleUrl,{headers})).json();
 const result=await page.request.post(scheduleUrl,{headers,data:{workShiftId:shifts.items.find(x=>x.shiftName===shiftName).id,effectiveFrom:fixture.today,concurrencyStamp:schedule.concurrencyStamp}});
 if(!result.ok())throw new Error(await result.text());
 await page.getByRole('button',{name:'Employee schedule',exact:true}).click();
 await page.getByText(shiftName+': 09:00 - 17:00',{exact:true}).waitFor();
 await page.screenshot({path:new URL('employee-schedule.png',out).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:new URL('employee-schedule-mobile.png',out).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);if(overflow)throw new Error('Mobile horizontal overflow');
 console.log('PASS: real HR create, independent school catalogue, dated employee assignment, desktop/mobile rendering.');
} catch(error) {console.log((await page.locator('body').innerText()).slice(-3500));throw error;} finally {await browser.close();}
