import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';

const output = path.resolve('.artifacts/attendance-register');
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const state = () => page.evaluate(() => window.attendanceFixture);
const checks = [];
try {
  await page.goto(process.env.REGISTER_FIXTURE_URL || 'http://localhost:5189/');
  await expect(page.getByRole('status')).toHaveText('65 staff found');
  await expect(page.getByRole('region', { name: 'Attendance register filters' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Go to next page' }).click();
  await expect.poll(async () => (await state()).query.skipCount).toBe(50);
  await expect(page.getByText('Synthetic Staff 51', { exact: true })).toBeVisible();
  checks.push('server paging');
  await page.getByRole('button', { name: 'Filters', exact: true }).click();
  await page.getByRole('combobox', { name: 'Divisions', exact: true }).click();
  await page.getByRole('option', { name: 'Primary / English', exact: true }).click();
  await page.getByRole('option', { name: 'Secondary / English', exact: true }).click();
  await page.getByRole('listbox', { name: 'Divisions' }).press('Escape');
  await expect.poll(async () => (await state()).query.skipCount).toBe(0);
  await expect(page.getByRole('status')).toHaveText('44 staff found');
  await page.getByRole('textbox', { name: 'Department contains' }).fill('Science');
  await expect(page.getByRole('status')).toHaveText('22 staff found');
  await page.getByRole('combobox', { name: 'Staff group' }).click();
  await page.getByRole('option', { name: 'Teaching', exact: true }).click();
  await page.getByRole('combobox', { name: 'Staff', exact: true }).fill('Synthetic Staff 05');
  await page.getByRole('option', { name: 'Synthetic Staff 05 (S5)' }).click();
  await expect(page.getByRole('status')).toHaveText('1 staff found');
  await page.getByRole('textbox', { name: 'Search table' }).fill('Staff 05');
  await expect.poll(async () => (await state()).query.search).toBe('Staff 05');
  await page.getByRole('button', { name: 'Sort by Staff' }).click();
  await expect.poll(async () => (await state()).query.sorting).toBe('employeeName asc');
  checks.push(
    'multiple divisions AND staff AND group AND department AND search; server sorting; page reset'
  );
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  await page.getByRole('menuitem', { name: /Excel/i }).click();
  await expect.poll(async () => (await state()).export?.query.employeeId).toBe('staff-5');
  const exported = (await state()).export;
  expect(exported.query.educationMediumStageIds).toEqual(['division-a', 'division-b']);
  expect(exported.query.department).toBe('Science');
  expect(exported.query.sorting).toBe('employeeName asc');
  expect(exported.request.searchTerm).toBe('Staff 05');
  expect(
    exported.request.columns.some((column) => column.id === 'select' || column.id === 'actions')
  ).toBe(false);
  checks.push('export captures composed criteria, sort and ordered data columns');
  await page.getByRole('button', { name: /^Filters \(/ }).click();
  await expect(page.getByRole('region', { name: 'Attendance register filters' })).toHaveCount(0);
  await expect(page.getByLabel('Applied register filters')).toBeVisible();
  await page.screenshot({ path: `${output}/desktop-filtered.png` });
  await page.getByRole('button', { name: 'Expand row 1', exact: true }).click();
  const edit = page.getByRole('button', { name: 'Adjust', exact: true });
  await edit.first().click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await dialog.getByRole('combobox').click();
  await page.getByRole('option', { name: 'Absent', exact: true }).click();
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect.poll(async () => (await state()).adjustments.length).toBe(1);
  expect((await state()).adjustments[0].attendanceId).toBe('staff-5-day');
  checks.push('filtered daily cell edit targets stable attendance ID');
  await page.getByRole('button', { name: /^Filters \(/ }).click();
  await page.getByRole('textbox', { name: 'Department contains' }).fill('No such department');
  await expect(page.getByRole('status')).toHaveText('0 staff found');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('65 staff found');
  await expect(page.getByRole('textbox', { name: 'Search table' })).toHaveValue('');
  expect((await state()).query.educationMediumStageIds).toEqual([]);
  expect((await state()).query.employeeId).toBe('');
  checks.push('empty intersection and full filter/search reset');
  const original = (await state()).query.startDate;
  await page.getByRole('button', { name: 'Previous month', exact: true }).click();
  await expect.poll(async () => (await state()).query.startDate).not.toBe(original);
  await page.getByRole('button', { name: 'Next month', exact: true }).click();
  await expect.poll(async () => (await state()).query.startDate).toBe(original);
  checks.push('month navigation preserves criteria');
  await page.getByRole('button', { name: 'Filters', exact: true }).click();
  await page.screenshot({ path: `${output}/desktop.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${output}/mobile.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Filters', exact: true }).press('Enter');
  await expect(page.getByRole('region', { name: 'Attendance register filters' })).toBeVisible();
  await page.getByRole('combobox', { name: 'Divisions', exact: true }).press('Space');
  await expect(page.getByRole('listbox', { name: 'Divisions' })).toBeVisible();
  await page.getByRole('listbox', { name: 'Divisions' }).press('Escape');
  await page.screenshot({ path: `${output}/mobile-filters.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  checks.push('390px mobile, keyboard panel/multiselect, no document horizontal overflow');
  expect(errors).toEqual([]);
  await fs.writeFile(`${output}/results.json`, JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
} finally {
  await browser.close();
}
