import type { FormikProps } from 'formik';

import { getIn } from 'formik';
import { TextField } from '@mui/material';
import ShakingTextField from 'src/components/shaking-text-field';

import type { BookFormValues } from '../Components/type';

export function CopyAccessionField({
  formik,
  index,
  disabled,
}: {
  formik: FormikProps<BookFormValues>;
  index: number;
  disabled: boolean;
}) {
  const copy = formik.values.copies[index];
  const persisted = Boolean(copy.copyId || copy.id);
  const automatic = !persisted && formik.values.isAccesionNumberAutoGenerated;
  const path = `copies.${index}.accessionNo`;
  const error = Boolean(getIn(formik.touched, path) && getIn(formik.errors, path));
  return (
    <ShakingTextField error={error}>
      <TextField
        name={path}
        label="Accession number"
        fullWidth
        size="small"
        value={copy.accessionNo}
        required={!automatic}
        disabled={disabled}
        InputProps={{ readOnly: persisted || automatic }}
        inputProps={{ maxLength: 50 }}
        onChange={formik.handleChange}
        onBlur={formik.handleBlur}
        error={error}
        helperText={
          error
            ? String(getIn(formik.errors, path))
            : persisted
              ? 'Saved accession numbers cannot change.'
              : automatic
                ? 'Allocated by the server when saved.'
                : 'Enter the printed accession number.'
        }
      />
    </ShakingTextField>
  );
}
