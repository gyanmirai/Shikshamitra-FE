import React from 'react';
import { Provider } from 'react-redux';
import { api } from 'src/redux/service';
import { http, HttpResponse } from 'msw';
import { mswServer } from 'src/test/mswServer';
import { configureStore } from '@reduxjs/toolkit';
import { act, renderHook } from '@testing-library/react';
import { it, vi, expect, describe, beforeEach } from 'vitest';
import { clearCachedAuthSession } from 'src/redux/session-cache';

import { useBookEditor } from './useBookEditor';
import { getInitialBookData } from '../Components/BookManageInitialValues';

vi.hoisted(() => {
  process.env.NEXT_PUBLIC_API_URL = 'http://library.test';
});
vi.mock('next-auth/react', () => ({ getSession: async () => null, signOut: vi.fn() }));

const savedBook = {
  id: 'saved-book',
  metadataRevision: 'metadata-saved',
  copiesRevision: 'copies-saved',
  title: 'વાર્તાઓ',
  author: 'Asha Patel',
  language: 0,
  categoryId: 'category-id',
  price: 125.25,
  priceText: '125.25',
  copies: [
    {
      copyId: 'saved-copy',
      copyNumber: 1,
      accessionNo: 'LIB-00042',
      status: 0,
      section: { id: 'section-id', name: 'Fiction' },
      shelf: { id: 'shelf-id', name: 'Shelf 1' },
    },
  ],
};

const createdResponse = {
  id: savedBook.id,
  metadataRevision: savedBook.metadataRevision,
  copiesRevision: savedBook.copiesRevision,
};

function setup() {
  const store = configureStore({
    reducer: { [api.reducerPath]: api.reducer },
    middleware: (defaults) => defaults().concat(api.middleware),
  });
  const wrapper = ({ children }: { children: React.ReactNode }) => (
    <Provider store={store}>{children}</Provider>
  );
  const initial = getInitialBookData({
    title: 'વાર્તાઓ',
    author: 'Asha Patel',
    language: 0,
    categoryId: 'category-id',
    price: 125.25,
    isAccesionNumberAutoGenerated: true,
    copies: [{ copyNo: 1, accessionNo: '', sectionId: 'section-id', shelfId: 'shelf-id' }],
  });
  return renderHook(() => useBookEditor(initial, 'year-id', true, false, vi.fn()), { wrapper });
}

beforeEach(clearCachedAuthSession);

describe('new book inventory saves', () => {
  it('keeps Next local and creates metadata with copies in one request for an Add-only user', async () => {
    const bodies: Record<string, unknown>[] = [];
    mswServer.use(
      http.post('http://library.test/api/library/books', async ({ request }) => {
        bodies.push((await request.json()) as Record<string, unknown>);
        return HttpResponse.json(createdResponse);
      }),
      http.get('http://library.test/api/library/books/saved-book', () =>
        HttpResponse.json(savedBook)
      )
    );
    const { result } = setup();
    await act(async () => {
      await result.current.saveCurrent(result.current.formik.values, true);
    });
    expect(result.current.activeStep).toBe(1);
    expect(bodies).toHaveLength(0);
    await act(async () => {
      await result.current.saveCurrent(result.current.formik.values, true);
    });
    expect(bodies).toHaveLength(1);
    expect(bodies[0]).toMatchObject({
      title: 'વાર્તાઓ',
      price: null,
      priceText: '125.25',
      numberOfCopies: 1,
      copies: [
        { copyNumber: 1, accessionNumber: null, sectionId: 'section-id', shelfId: 'shelf-id' },
      ],
    });
    expect(result.current.formik.values.copies[0]).toMatchObject({
      copyId: 'saved-copy',
      accessionNo: 'LIB-00042',
      section: 'section-id',
      shelf: 'shelf-id',
    });
    expect(result.current.formik.dirty).toBe(false);
    expect(result.current.completed).toBe(true);
  });

  it('retries only the read when persistence succeeds and the reload fails', async () => {
    let creates = 0;
    let reads = 0;
    mswServer.use(
      http.post('http://library.test/api/library/books', () => {
        creates += 1;
        return HttpResponse.json(createdResponse);
      }),
      http.get('http://library.test/api/library/books/saved-book', () => {
        reads += 1;
        return reads === 1
          ? HttpResponse.json({ detail: 'Reload unavailable.' }, { status: 500 })
          : HttpResponse.json(savedBook);
      })
    );
    const { result } = setup();
    await act(async () => {
      await result.current.saveCurrent(result.current.formik.values, true);
    });
    await act(async () => {
      await result.current.saveCurrent(result.current.formik.values, true);
    });
    expect(result.current.reloadId).toBe('saved-book');
    expect(result.current.formik.values.title).toBe('વાર્તાઓ');
    await act(async () => {
      await result.current.saveCurrent(result.current.formik.values, true);
    });
    expect(creates).toBe(1);
    expect(reads).toBe(2);
    expect(result.current.completed).toBe(true);
  });
});
