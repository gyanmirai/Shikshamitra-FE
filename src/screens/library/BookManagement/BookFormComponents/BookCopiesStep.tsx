import type { FormikProps, FormikErrors } from 'formik';

import { Grid } from '@mui/system';
// eslint-disable-next-line import/no-extraneous-dependencies
import Barcode from 'react-barcode';
import { useState, useEffect } from 'react';
import { GlobalIcons } from 'src/utils/icons';
import { Iconify } from 'src/components/iconify';
import CustomDialog from 'src/components/customDialog';
import CustomSelect from 'src/components/custom-select';
import CustomTooltip from 'src/components/custom-tooltip';
import ShakingTextField from 'src/components/shaking-text-field';
import CustomizableTable from 'src/components/customizabaleTable';
import { LibraryBookStatus } from 'src/enums/library-book-status';
import { Box, Button, TextField, IconButton, Typography } from '@mui/material';

import type { IBookCopy, IBookPayload } from '../Components/type';

interface BookCopiesStepProps {
  formik: FormikProps<IBookPayload>;
}

const BookCopiesStep = ({ formik }: BookCopiesStepProps) => {
  const [copies, setCopies] = useState<IBookCopy[]>(formik.values.copies || []);
  const [openAccessionDialog, setOpenAccessionDialog] = useState(false);

  useEffect(() => {
    const newCopies = Array.from({ length: formik.values.numberOfCopies }, (_, i) => ({
      copyNo: i + 1,
      accessionNo: formik.values.isAccesionNumberAutoGenerated
        ? `ACC-${String(i + 1).padStart(4, '0')}`
        : '',
      status: LibraryBookStatus.Available,
      section: formik.values.copies?.[i]?.section || '',
      shelf: formik.values.copies?.[i]?.shelf || '',
    }));

    setCopies(newCopies as IBookCopy[]);
    formik.setFieldValue('copies', newCopies);
    // Validate only the newly generated fields: copyNo, accessionNo and status
    newCopies.forEach((_, idx) => {
      formik.setFieldTouched(`copies.${idx}.copyNo`, false, false);
      formik.setFieldTouched(`copies.${idx}.accessionNo`, false, false);
      formik.setFieldTouched(`copies.${idx}.status`, false, false);
    });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [formik.values.isAccesionNumberAutoGenerated, formik.values.numberOfCopies]);

  return (
    <Box>
      <hr style={{ border: 'none', borderTop: '1px solid #e0e0e0', margin: '16px 0' }} />
      <Box
        sx={{
          display: 'flex',
          justifyContent: 'right',
          gap: 2,
          alignItems: 'center',
          position: 'sticky',
          top: 0,
          zIndex: 10,
          backgroundColor: 'background.paper',
          p: 1,
        }}
      >
        {' '}
        <Box sx={{ display: 'flex', alignItems: 'center', gap: 1 }}>
          <Button
            variant="contained"
            color="inherit"
            size="small"
            onClick={() =>
              formik.setFieldValue(
                'isAccesionNumberAutoGenerated',
                !formik.values.isAccesionNumberAutoGenerated
              )
            }
            startIcon={<Iconify icon="mdi:autorenew" />}
          >
            Auto Accession
          </Button>
        </Box>
        <Box sx={{ display: 'flex' }}>
          <Button
            variant="contained"
            size="small"
            onClick={() => setOpenAccessionDialog(true)}
            startIcon={<Iconify icon={GlobalIcons.download} />}
          >
            Accession label
          </Button>
        </Box>
      </Box>
      {copies.length > 0 && (
        <Box sx={{ height: '100%', display: 'flex', flexDirection: 'column' }}>
          <CustomizableTable
            tableContainerProps={{
              component: 'div', // override Scrollbar to avoid nested wrappers breaking sticky
              sx: {
                maxHeight: 420,
                overflowY: 'auto',
                // Reinforce sticky header styling (fallback if internal styles fail)
                '& thead th': {
                  position: 'sticky',
                  top: 0,
                  zIndex: 3,
                  backgroundColor: 'background.paper',
                },
              },
            }}
            tableId="copies-table"
            isSearch={false}
            isFilter={false}
            columns={[
              {
                id: 'copyNo',
                label: 'Copy No.',
                align: 'left',
                minWidth: 100,
                render: (_, row) => <span>{row.copyNo}</span>,
              },
              {
                id: 'accessionNo',
                label: '',
                renderColumn(value) {
                  return (
                    <Box display="flex" alignItems="center" gap={1}>
                      Accession No.
                      <CustomTooltip
                        arrow
                        placement="right"
                        sx={{ textAlign: 'justify' }}
                        title="Enter the unique Accession Number for this copy. Only letters, numbers, and hyphens are allowed. Maximum 12 characters."
                      >
                        <Iconify
                          icon="lucide:info"
                          sx={{ cursor: 'pointer', width: 15, height: 15 }}
                          color="info.main"
                        />
                      </CustomTooltip>
                    </Box>
                  );
                },
                minWidth: 170,
                align: 'left',
                render: (value, row) => (
                  <Box mb={1}>
                    <ShakingTextField
                      error={
                        !!(
                          formik?.touched?.copies?.[row.copyNo - 1]?.accessionNo &&
                          Array.isArray(formik?.errors?.copies) &&
                          typeof formik?.errors?.copies?.[row.copyNo - 1] === 'object' &&
                          (formik.errors.copies[row.copyNo - 1] as FormikErrors<IBookCopy>)
                            ?.accessionNo
                        )
                      }
                    >
                      <TextField
                        size="small"
                        fullWidth
                        label="Accession No *"
                        value={formik.values.copies[row.copyNo - 1]?.accessionNo || ''}
                        onChange={(e) => {
                          const val = e.target.value
                            .replace(/[^a-zA-Z0-9-]/g, '')
                            .split(' ')
                            .map((word) => word || '')
                            .join(' ');

                          if (val.length <= 11) {
                            formik.setFieldValue(`copies.${row.copyNo - 1}.accessionNo`, val);
                            const updated = [...copies];
                            updated[row.copyNo - 1].accessionNo = val;
                            setCopies(updated);
                            formik.setFieldTouched(
                              `copies.${row.copyNo - 1}.accessionNo`,
                              false,
                              false
                            );
                          }
                        }}
                        error={
                          !!(
                            formik?.touched?.copies?.[row.copyNo - 1]?.accessionNo &&
                            Array.isArray(formik?.errors?.copies) &&
                            typeof formik?.errors?.copies?.[row.copyNo - 1] === 'object' &&
                            (formik.errors.copies[row.copyNo - 1] as FormikErrors<IBookCopy>)
                              ?.accessionNo
                          )
                        }
                        helperText={
                          (formik?.touched?.copies?.[row.copyNo - 1]?.accessionNo &&
                            Array.isArray(formik?.errors?.copies) &&
                            typeof formik?.errors?.copies?.[row.copyNo - 1] === 'object' &&
                            (formik.errors.copies[row.copyNo - 1] as FormikErrors<IBookCopy>)
                              ?.accessionNo) ||
                          ''
                        }
                      />
                    </ShakingTextField>
                  </Box>
                ),
              },
              {
                id: 'section',
                label: 'Section',
                align: 'left',
                minWidth: 170,
                render: (_, row) => (
                  <Box mb={1}>
                    <ShakingTextField
                      error={
                        !!(
                          formik?.touched?.copies?.[row.copyNo - 1]?.section &&
                          Array.isArray(formik?.errors?.copies) &&
                          typeof formik?.errors?.copies?.[row.copyNo - 1] === 'object' &&
                          (formik.errors.copies[row.copyNo - 1] as FormikErrors<IBookCopy>)?.section
                        )
                      }
                    >
                      <CustomSelect
                        label="Section *"
                        options={[
                          { value: 'section_1', label: 'Section 1' },
                          { value: 'section_2', label: 'Section 2' },
                          { value: 'section_3', label: 'Section 3' },
                          { value: 'section_4', label: 'Section 4' },
                          { value: 'section_5', label: 'Section 5' },
                        ]}
                        name="section"
                        value={formik.values.copies[row.copyNo - 1]?.section || ''}
                        onChange={(val) => {
                          const updated = [...copies];
                          updated[row.copyNo - 1].section = val as string;
                          setCopies(updated);
                          formik.setFieldValue('copies', updated);
                          formik.setFieldTouched(`copies.${row.copyNo - 1}.section`, false, false);
                        }}
                        helperText={
                          (formik?.touched?.copies?.[row.copyNo - 1]?.section &&
                            Array.isArray(formik?.errors?.copies) &&
                            typeof formik?.errors?.copies?.[row.copyNo - 1] === 'object' &&
                            (formik.errors.copies[row.copyNo - 1] as FormikErrors<IBookCopy>)
                              ?.section) ||
                          ''
                        }
                        error={
                          !!(
                            formik?.touched?.copies?.[row.copyNo - 1]?.section &&
                            Array.isArray(formik?.errors?.copies) &&
                            typeof formik?.errors?.copies?.[row.copyNo - 1] === 'object' &&
                            (formik.errors.copies[row.copyNo - 1] as FormikErrors<IBookCopy>)
                              ?.section
                          )
                        }
                        formControlProps={{ sx: { minWidth: 200 } }}
                      />
                    </ShakingTextField>
                  </Box>
                ),
              },
              {
                id: 'shelf',
                label: 'Shelf',
                align: 'left',
                minWidth: 170,
                render: (_, row) => (
                  <Box mb={1}>
                    <ShakingTextField
                      error={
                        !!(
                          formik?.touched?.copies?.[row.copyNo - 1]?.shelf &&
                          Array.isArray(formik?.errors?.copies) &&
                          typeof formik?.errors?.copies?.[row.copyNo - 1] === 'object' &&
                          (formik.errors.copies[row.copyNo - 1] as FormikErrors<IBookCopy>)?.shelf
                        )
                      }
                    >
                      <CustomSelect
                        label="Shelf *"
                        options={[
                          { value: 'shelf_a', label: 'Shelf A' },
                          { value: 'shelf_b', label: 'Shelf B' },
                          { value: 'shelf_c', label: 'Shelf C' },
                          { value: 'shelf_d', label: 'Shelf D' },
                          { value: 'shelf_e', label: 'Shelf E' },
                        ]}
                        name="shelf"
                        value={formik.values.copies[row.copyNo - 1]?.shelf || ''}
                        onChange={(val) => {
                          const updated = [...copies];
                          updated[row.copyNo - 1].shelf = val as string;
                          setCopies(updated);
                          formik.setFieldValue('copies', updated);
                          formik.setFieldTouched(`copies.${row.copyNo - 1}.shelf`, false, false);
                        }}
                        helperText={
                          (formik?.touched?.copies?.[row.copyNo - 1]?.shelf &&
                            Array.isArray(formik?.errors?.copies) &&
                            typeof formik?.errors?.copies?.[row.copyNo - 1] === 'object' &&
                            (formik.errors.copies[row.copyNo - 1] as FormikErrors<IBookCopy>)
                              ?.shelf) ||
                          ''
                        }
                        error={
                          !!(
                            formik?.touched?.copies?.[row.copyNo - 1]?.shelf &&
                            Array.isArray(formik?.errors?.copies) &&
                            typeof formik?.errors?.copies?.[row.copyNo - 1] === 'object' &&
                            (formik.errors.copies[row.copyNo - 1] as FormikErrors<IBookCopy>)?.shelf
                          )
                        }
                        formControlProps={{ sx: { minWidth: 200 } }}
                        disabled={!formik.values.copies[row.copyNo - 1]?.section}
                      />
                    </ShakingTextField>
                  </Box>
                ),
              },
              {
                id: 'barcode',
                label: 'Barcode',
                align: 'left',
                isFilter: false,
                isSort: false,
                minWidth: 100,
                render: (_, row) =>
                  row.accessionNo ? (
                    <Barcode
                      value={row.accessionNo}
                      format="CODE128" // other options: EAN13, UPC, etc.
                      width={1}
                      height={20}
                      displayValue
                      background="#ffffff"
                      lineColor="#000000"
                    />
                  ) : (
                    <Typography variant="caption" color="text.secondary">
                      Accession number pending
                    </Typography>
                  ),
              },
              {
                id: '',
                label: 'Print',
                isFilter: false,
                isSort: false,
                render: (_, row) => (
                  <IconButton onClick={() => {}}>
                    <Iconify icon={GlobalIcons.printer} />
                  </IconButton>
                ),
              },
            ]}
            data={formik.values.copies || []}
          />
        </Box>
      )}

      <CustomDialog
        open={openAccessionDialog}
        handleClose={() => setOpenAccessionDialog(false)}
        maxWidth="sm"
        title={
          <Box display="flex" flexDirection="row" gap={1} alignItems="center">
            <Typography variant="h5">Generate Accession Label</Typography>
            <CustomTooltip
              arrow
              placement="right"
              sx={{ textAlign: 'justify' }}
              title="Download or print accession labels for all book copies listed below."
            >
              <Iconify icon="lucide:info" sx={{ cursor: 'pointer' }} color="info.main" />
            </CustomTooltip>
          </Box>
        }
      >
        <Box
          sx={{
            maxHeight: 400,
            overflowY: 'auto',
            pr: 1,
            paddingLeft: 2,
            paddingRight: 2,
          }}
        >
          {copies.some((copy) => !copy.accessionNo) && (
            <Box
              sx={{
                p: 2,
                backgroundColor: '#ffebee',
                borderRadius: 2,
                border: '1px solid #f44336',
                color: '#d32f2f',
                textAlign: 'left',
                mb: 2,
                width: '100%',
                fontWeight: 500,
                display: 'flex',
                alignItems: 'center',
                boxSizing: 'border-box',
              }}
            >
              Accession number pending
            </Box>
          )}

          <Grid container spacing={2} justifyContent="center" alignItems="center">
            {copies.map((copy, idx) =>
              copy.accessionNo ? (
                <Grid size={{ xs: 12, sm: 4 }} key={idx} display="flex" justifyContent="center">
                  <Box
                    sx={{
                      background: '#fff',
                      borderRadius: 2,
                      boxShadow: 'var(--shadows-8)',
                      p: 2,
                      mb: 2,
                      display: 'flex',
                      flexDirection: 'column',
                      alignItems: 'center',
                      width: 'fit-content',
                    }}
                  >
                    <Barcode
                      value={copy.accessionNo}
                      format="CODE128"
                      width={1}
                      height={60}
                      displayValue
                      background="#ffffff"
                      lineColor="#000000"
                    />
                  </Box>
                </Grid>
              ) : null
            )}
          </Grid>
        </Box>
      </CustomDialog>
    </Box>
  );
};

export default BookCopiesStep;
