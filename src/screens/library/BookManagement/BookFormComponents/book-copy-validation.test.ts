import { it, expect, describe } from 'vitest';

import { bookValidationSchema } from './BookManageValidation';

const copy = (accessionNo: string, copyNo = 1) => ({
  copyNo,
  accessionNo,
  section: 'section-id',
  shelf: 'shelf-id',
});

describe('library copy identity validation', () => {
  it('allows new blank accessions only when the server will allocate them', async () => {
    const values = {
      isAccesionNumberAutoGenerated: true,
      numberOfCopies: 2,
      copies: [copy('', 1), copy('', 2)],
    };

    await expect(bookValidationSchema[1].validate(values)).resolves.toMatchObject(values);
    await expect(
      bookValidationSchema[1].validate({ ...values, isAccesionNumberAutoGenerated: false })
    ).rejects.toThrow('Accession number is required');
  });

  it('rejects duplicate printed accessions regardless of case or surrounding spaces', async () => {
    await expect(
      bookValidationSchema[1].validate({
        numberOfCopies: 2,
        copies: [copy(' Acc-001 ', 1), copy('acc-001', 2)],
      })
    ).rejects.toThrow('Accession numbers must be unique');
  });
});
