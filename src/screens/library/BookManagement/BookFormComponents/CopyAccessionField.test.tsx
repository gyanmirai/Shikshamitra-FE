import React from 'react';
import { useFormik } from 'formik';
import { it, expect, describe } from 'vitest';
import { render, screen, waitFor, fireEvent } from '@testing-library/react';

import { CopyAccessionField } from './CopyAccessionField';
import { getInitialBookData } from '../Components/BookManageInitialValues';

function Harness({ persisted = false }: { persisted?: boolean }) {
  const formik = useFormik({
    initialValues: getInitialBookData({
      isAccesionNumberAutoGenerated: false,
      copies: [{ copyId: persisted ? 'copy-id' : undefined, copyNo: 9, accessionNo: 'PRINT-9' }],
    }),
    onSubmit: () => undefined,
  });
  return (
    <>
      <CopyAccessionField formik={formik} index={0} disabled={false} />
      <output data-testid="draft-accession">{formik.values.copies[0].accessionNo}</output>
    </>
  );
}

describe('stable accession editing', () => {
  it('updates the correct array row when its saved copy number is not an array position', async () => {
    render(<Harness />);
    fireEvent.change(screen.getByLabelText(/Accession number/), { target: { value: 'PRINT-10' } });
    await waitFor(() =>
      expect(screen.getByTestId('draft-accession')).toHaveTextContent('PRINT-10')
    );
  });

  it('exposes saved accession numbers as read-only', () => {
    render(<Harness persisted />);
    expect(screen.getByLabelText(/Accession number/)).toHaveAttribute('readonly');
    expect(screen.getByTestId('draft-accession')).toHaveTextContent('PRINT-9');
  });
});
