import * as yup from 'yup';

import { cataloguePriceSchema } from './catalogue-price-schema';

const wholeNumber = (label: string, maximum: number) =>
  yup
    .number()
    .transform((value, raw) => (raw === '' ? undefined : value))
    .typeError(`${label} must be a whole number`)
    .required(`${label} is required`)
    .integer(`${label} must be a whole number`)
    .min(0)
    .max(maximum);

const stockCount = () =>
  wholeNumber('Number of copies', 1000).when('id', {
    is: (id: unknown) => Boolean(id),
    then: (schema) => schema.max(2147483647),
  });

export const generalBookSchema = yup.object({
  title: yup.string().trim().required('Title is required').min(2).max(100),
  author: yup.string().trim().required('Author is required').max(256),
  categoryId: yup.string().required('Category is required'),
  language: yup.number().nullable().required('Language is required').oneOf([0, 1, 2, 3, 4]),
  isbn: yup
    .string()
    .trim()
    .max(30)
    .test('isbn', 'Enter an ISBN-10 or ISBN-13, or leave it blank.', (value) => {
      if (!value) return true;
      return /^(?:[0-9]{9}[0-9Xx]|[0-9]{13})$/.test(value.replace(/[\s-]/g, ''));
    }),
  numberOfCopies: stockCount(),
  numberOfPages: yup
    .number()
    .transform((value, raw) => (raw === '' ? 0 : value))
    .integer()
    .min(0)
    .max(100000),
  price: cataloguePriceSchema(),
});

export const copiesBookSchema = yup
  .object({
    id: yup.string().optional(),
    isAccesionNumberAutoGenerated: yup.boolean(),
    numberOfCopies: stockCount(),
    copies: yup
      .array()
      .of(
        yup.object({
          id: yup.string().optional(),
          copyId: yup.string().optional(),
          copyNo: yup.number().required('Copy number is required').integer().min(1),
          accessionNo: yup.string().trim().max(50, 'Accession number cannot exceed 50 characters.'),
          section: yup.string().required('Section is required'),
          shelf: yup.string().required('Shelf is required'),
        })
      )
      .required()
      .max(1000)
      .when('id', {
        is: (id: unknown) => Boolean(id),
        then: (schema) =>
          schema
            .max(2147483647)
            .test(
              'new-copy-limit',
              'Add no more than 1000 new copies in this editor.',
              (copies) => (copies || []).filter((copy) => !copy.copyId && !copy.id).length <= 1000
            ),
      })
      .test('unique-accessions', 'Accession numbers must be unique', (copies) => {
        const accessions = (copies || [])
          .map((copy) => copy.accessionNo?.trim().toUpperCase())
          .filter(Boolean);
        return new Set(accessions).size === accessions.length;
      })
      .test('unique-copy-numbers', 'Copy numbers must be unique', (copies) => {
        const numbers = (copies || []).map((copy) => copy.copyNo);
        return new Set(numbers).size === numbers.length;
      })
      .test(
        'copy-count',
        'Number of copy rows must match the requested number of copies.',
        function (copies) {
          return (copies?.length || 0) === Number(this.parent.numberOfCopies);
        }
      ),
  })
  .test(
    'new-book-copies',
    'Add at least one copy before submitting a new book.',
    (value) => Boolean(value.id) || value.copies.length > 0
  )
  .test('accession-required', 'Accession number is required', function (value) {
    const index = value.copies.findIndex(
      (copy) =>
        !copy.accessionNo?.trim() &&
        (Boolean(copy.copyId || copy.id) || !value.isAccesionNumberAutoGenerated)
    );
    return (
      index < 0 ||
      this.createError({
        path: `copies.${index}.accessionNo`,
        message: 'Accession number is required',
      })
    );
  });

export const bookValidationSchema = [
  generalBookSchema,
  copiesBookSchema,
  generalBookSchema.concat(copiesBookSchema),
];
