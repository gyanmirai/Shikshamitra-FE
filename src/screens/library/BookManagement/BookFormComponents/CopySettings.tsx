import type { FormikProps } from 'formik';

import { GlobalIcons } from 'src/utils/icons';
import { Iconify } from 'src/components/iconify';
import { FormSectionCard } from 'src/components/form-section-card';
import { Alert, Stack, Button, Checkbox, FormControlLabel } from '@mui/material';

import { resizeDraftCopies } from './book-form-model';

import type { BookFormValues } from '../Components/type';

export function CopySettings({
  formik,
  disabled,
  printDisabled,
  onLabels,
}: {
  formik: FormikProps<BookFormValues>;
  disabled: boolean;
  printDisabled: boolean;
  onLabels: () => void;
}) {
  const removed = formik.initialValues.copies.filter(
    (copy) =>
      (copy.copyId || copy.id) &&
      !formik.values.copies.some(
        (current) => (current.copyId || current.id) === (copy.copyId || copy.id)
      )
  );
  const replaceCopies = (copies: BookFormValues['copies']) =>
    formik.setValues({ ...formik.values, copies, numberOfCopies: String(copies.length) });
  return (
    <FormSectionCard
      title="Copy Settings"
      icon={GlobalIcons.copy}
      descriptionTooltip="Each row represents one physical copy. Saved copy numbers and printed accession numbers remain unchanged."
    >
      <Stack
        direction={{ xs: 'column', sm: 'row' }}
        spacing={1}
        useFlexGap
        flexWrap="wrap"
        alignItems={{ sm: 'center' }}
      >
        <FormControlLabel
          control={
            <Checkbox
              checked={formik.values.isAccesionNumberAutoGenerated}
              disabled={disabled}
              onChange={(_, value) => formik.setFieldValue('isAccesionNumberAutoGenerated', value)}
            />
          }
          label="Allocate accession numbers automatically for new copies"
        />
        <Button
          name="copies"
          type="button"
          size="small"
          variant="outlined"
          color="inherit"
          disabled={disabled || formik.values.copies.length >= 1000}
          onClick={() =>
            replaceCopies(resizeDraftCopies(formik.values.copies, formik.values.copies.length + 1))
          }
          startIcon={<Iconify icon={GlobalIcons.addIcon} />}
        >
          Add copy
        </Button>
        {removed.length > 0 && (
          <Button
            type="button"
            size="small"
            color="inherit"
            disabled={disabled}
            onClick={() => replaceCopies([...formik.values.copies, ...removed])}
          >
            Restore removed copies
          </Button>
        )}
        <Button
          type="button"
          size="small"
          variant="outlined"
          color="inherit"
          disabled={printDisabled || !formik.values.id || formik.dirty}
          onClick={onLabels}
          startIcon={<Iconify icon={GlobalIcons.printer} />}
        >
          Saved labels
        </Button>
      </Stack>
      {formik.dirty && (
        <Alert severity="info">Save changes before printing updated copy labels.</Alert>
      )}
      {formik.values.copies.some((copy) => copy.copyId || copy.id) && (
        <Alert severity="info">
          Saved copy locations are read-only here. Open Inventory actions for the copy and choose
          Move to record a location change with its reason.
        </Alert>
      )}
    </FormSectionCard>
  );
}
