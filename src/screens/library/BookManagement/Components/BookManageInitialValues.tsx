import type { IBookPayload } from './type';

export const getInitialBookData = (
  editData?: (Partial<IBookPayload> & { id?: string }) | null
): IBookPayload => ({
  id: editData?.id || '',
  title: editData?.title || '',
  isbn: editData?.isbn || '',
  author: editData?.author || '',
  publisher: editData?.publisher || '',
  subject: editData?.subject || '',
  category: editData?.category || '',
  edition: editData?.edition || '',
  language: editData?.language || '',
  price: editData?.price || 0,
  numberOfCopies: editData?.numberOfCopies || 0,
  numberOfPages: editData?.numberOfPages || 0,
  classes: editData?.classes || [],
  vendor: editData?.vendor || '',
  bookCoverImages: editData?.bookCoverImages || '',
  copies: editData?.copies || [],
  isAccesionNumberAutoGenerated: editData?.isAccesionNumberAutoGenerated || false,
  applicableAge: editData?.applicableAge || [],
});
