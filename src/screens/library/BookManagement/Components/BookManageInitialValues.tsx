import { cataloguePriceDraft } from 'src/redux/library/catalogue-price';
import { catalogueLanguageCode } from 'src/redux/library/catalogue-metadata';

import { normalizeFormCopy, resizeDraftCopies } from '../BookFormComponents/book-form-model';

import type { BookFormValues } from './type';
import type { BookSource } from '../BookFormComponents/book-form-model';

export const getInitialBookData = (editData?: BookSource | null): BookFormValues => ({
  id: editData?.id || '',
  metadataRevision: editData?.metadataRevision,
  copiesRevision: editData?.copiesRevision,
  title: editData?.title || '',
  isbn: editData?.isbn || '',
  author: editData?.author || '',
  publisher: editData?.publisher || '',
  subject: editData?.subject || '',
  categoryId: editData?.categoryId || '',
  edition: editData?.edition || '',
  language: editData?.language ?? null,
  languageCode: editData ? catalogueLanguageCode(editData) : null,
  languageLabel: editData?.languageLabel ?? null,
  materialCode: editData?.materialCode ?? null,
  materialLabel: editData?.materialLabel ?? null,
  expectedCatalogueConfigurationRevision: editData?.expectedCatalogueConfigurationRevision,
  price: cataloguePriceDraft(editData),
  numberOfCopies: String(
    editData?.copies ? editData.copies.length : (editData?.numberOfCopies ?? 1)
  ),
  numberOfPages: String(editData?.numberOfPages ?? editData?.pages ?? 0),
  classes: editData?.classes || [],
  vendor: editData?.vendor || '',
  coverImage: editData?.coverImage || '',
  copies: editData?.copies
    ? editData.copies.map(normalizeFormCopy)
    : resizeDraftCopies([], editData?.numberOfCopies ?? 1),
  isAccesionNumberAutoGenerated: editData?.isAccesionNumberAutoGenerated ?? !editData?.id,
  applicableAge: editData?.applicableAge || '',
});
