import type { SalaryDocumentPresentation } from 'src/redux/hr/payslip-api';

import { GlobalIcons } from 'src/utils/icons';
import { Iconify } from 'src/components/iconify';
import { useRef, useState, useEffect, useCallback } from 'react';
import { FormSectionCard } from 'src/components/form-section-card';
import { usePreviewPayslipSettingsMutation } from 'src/redux/hr/payslip-api';
import { Box, Stack, Alert, Button, Skeleton, Typography } from '@mui/material';

import PayslipPdfViewer from './payslip-pdf-viewer';

export default function PayslipSettingsPreview({
  presentation,
  brandingKey,
}: {
  presentation: SalaryDocumentPresentation;
  brandingKey: string;
}) {
  const [preview] = usePreviewPayslipSettingsMutation();
  const [result, setResult] = useState<{ key: string; url?: string; error?: boolean }>();
  const [retry, setRetry] = useState(0);
  const contentRef = useRef<HTMLDivElement>(null);
  const onReady = useCallback(() => {}, []);
  // Statement columns and delivery preferences do not affect the payslip PDF.
  const key = JSON.stringify({
    ...presentation,
    statementColumns: [],
    registerColumns: [],
    brandingKey,
  });
  useEffect(() => {
    let active = true;
    let url: string | undefined;
    let request: ReturnType<typeof preview> | undefined;
    const timer = window.setTimeout(() => {
      const { brandingKey: _, ...options } = JSON.parse(key);
      request = preview(options);
      request
        .unwrap()
        .then((blob) => {
          if (!active) return;
          url = URL.createObjectURL(blob);
          setResult({ key, url });
        })
        .catch(() => {
          if (active) setResult({ key, error: true });
        });
    }, 350);
    return () => {
      active = false;
      window.clearTimeout(timer);
      request?.abort();
      if (url) URL.revokeObjectURL(url);
    };
  }, [key, preview, retry]);
  const current = result?.key === key ? result : undefined;
  return (
    <FormSectionCard
      icon={GlobalIcons.pdf}
      title="Live Payslip Preview"
      descriptionTooltip="Generated by the same PDF renderer used for issued payslips, using your current unsaved appearance settings."
      sx={{ minWidth: 0 }}
    >
      <Typography variant="body2" color="text.secondary">
        Synthetic sample | A4 PDF | No real employee or salary data
      </Typography>
      <Typography variant="caption" color="text.secondary">
        School branding comes from Institute Setup. A missing school logo leaves a clean text
        header. Statement columns and email delivery do not change this payslip preview.
      </Typography>
      {current?.error ? (
        <Alert
          severity="error"
          action={
            <Button
              size="small"
              onClick={() => {
                setResult(undefined);
                setRetry((value) => value + 1);
              }}
            >
              Retry preview
            </Button>
          }
        >
          The sample PDF could not be generated. Your settings have been kept.
        </Alert>
      ) : current?.url ? (
        <>
          <Stack direction="row" justifyContent="flex-end">
            <Button
              component="a"
              href={current.url}
              download="synthetic-payslip-preview.pdf"
              size="small"
              startIcon={<Iconify icon={GlobalIcons.download} />}
            >
              Download sample PDF
            </Button>
          </Stack>
          <Box
            sx={{
              bgcolor: 'background.neutral',
              p: { xs: 1, sm: 2 },
              borderRadius: 1,
              minWidth: 0,
            }}
          >
            <PayslipPdfViewer
              url={current.url}
              title="Synthetic sample payslip"
              contentRef={contentRef}
              onReady={onReady}
            />
          </Box>
        </>
      ) : (
        <Stack spacing={1} role="status" aria-label="Updating sample payslip preview">
          <Typography variant="caption" color="text.secondary">
            Updating sample preview...
          </Typography>
          <Skeleton
            variant="rounded"
            sx={{ width: '100%', aspectRatio: '210 / 297', height: 'auto' }}
          />
        </Stack>
      )}
    </FormSectionCard>
  );
}
