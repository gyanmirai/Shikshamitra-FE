export type SessionBookingPreview = AssessmentBookingPreview;
export type SessionSetupValues = {
  name: string;
  nameAutoGenerated: boolean;
  sessionType: SharedSessionInput['sessionType'];
  classIds: string[];
  offeringIds: string[];
  stageIds: Record<string, string>;
  roomId: string;
  interviewerId: string;
  interviewerName: string;
  startsAt: Dayjs | null;
  endsAt: Dayjs | null;
  capacity: number | '';
  slotDurationMinutes: number | '';
  breakMinutes: number | '';
  bookings: SessionBookingCandidate[];
};
export type SharedSessionView = AssessmentSession;

export function setSessionScheduleDate(
  values: SessionSetupValues,
  date: Dayjs | null
): SessionSetupValues {
  const atTime = (previous: Dayjs | null) =>
    date
      ? date
          .hour(previous?.isValid() ? previous.hour() : 0)
          .minute(previous?.isValid() ? previous.minute() : 0)
          .second(0)
          .millisecond(0)
      : null;
  return { ...values, startsAt: atTime(values.startsAt), endsAt: atTime(values.endsAt) };
}

export function sessionSetupInitialValues(session?: SharedSessionView | null): SessionSetupValues {
  const scopes = session?.scopes?.length
    ? session.scopes
    : session
      ? [
          {
            admissionOfferingId: session.admissionOfferingId,
            workflowStageDefinitionId: session.workflowStageDefinitionId,
          },
        ]
      : [];
  return {
    name: session?.name ?? '',
    nameAutoGenerated: !session,
    sessionType: session?.sessionType ?? 'exam',
    classIds: [],
    offeringIds: scopes.map((s) => s.admissionOfferingId),
    stageIds: Object.fromEntries(
      scopes.map((s) => [s.admissionOfferingId, s.workflowStageDefinitionId])
    ),
    roomId: session?.roomId ?? '',
    interviewerId: session?.interviewerId ?? '',
    interviewerName: session?.interviewerName ?? '',
    startsAt: session ? dayjs(session.startsAt) : null,
    endsAt: session ? dayjs(session.endsAt) : null,
    capacity: session?.capacity ?? '',
    slotDurationMinutes: session?.slotDurationMinutes ?? 15,
    breakMinutes: session?.breakMinutes ?? 0,
    bookings: [],
  };
}

export function sessionSetupSchema(
  scopes: AssessmentScope[],
  rooms: SessionRoomChoice[],
  bookedCount = 0,
  review = false,
  allowStartedInterview = false
) {
  return Yup.object({
    name: Yup.string()
      .trim()
      .required('Session name is required')
      .max(128, 'Use at most 128 characters'),
    sessionType: Yup.string().oneOf(['exam', 'individualInterview', 'groupInterview']).required(),
    offeringIds: Yup.array()
      .of(Yup.string().required())
      .min(1, 'Select at least one class and its assessment')
      .max(20, 'Select at most 20 classes'),
    classIds: Yup.array().test(
      'resolved-classes',
      'Select an assessment for every selected class',
      function valid(value) {
        return (value ?? []).every((id) =>
          scopes.some(
            (scope) =>
              sessionClassKey(scope) === id &&
              this.parent.offeringIds.includes(scope.admissionOfferingId) &&
              this.parent.stageIds[scope.admissionOfferingId] === scope.workflowStageDefinitionId
          )
        );
      }
    ),
    stageIds: Yup.mixed().test(
      'valid-stages',
      'Select a valid assessment stage for every Offering',
      function valid(value) {
        return this.parent.offeringIds.every((id: string) =>
          scopes.some(
            (s) =>
              s.admissionOfferingId === id &&
              s.workflowStageDefinitionId === (value as Record<string, string>)?.[id]
          )
        );
      }
    ),
    roomId: Yup.string()
      .required('Select an Institute room')
      .test(
        'active-room',
        'Select an available Institute room',
        (value) => !value || rooms.some((r) => r.id === value && r.capacity > 0)
      ),
    interviewerId: Yup.string().when('sessionType', {
      is: (value: string) => value !== 'exam',
      then: (schema) => schema.required('Select an interviewer'),
    }),
    startsAt: Yup.mixed<Dayjs>()
      .nullable()
      .required('Start date and time are required')
      .test('start', 'Choose a valid future start time', function valid(value) {
        return Boolean(
          value?.isValid() &&
          (value.valueOf() > Date.now() ||
            (allowStartedInterview &&
              this.parent.sessionType === 'individualInterview' &&
              this.parent.endsAt?.isValid() &&
              this.parent.endsAt.valueOf() > Date.now()))
        );
      }),
    endsAt: Yup.mixed<Dayjs>()
      .nullable()
      .required('End date and time are required')
      .test('end', 'End must be after start', function valid(value) {
        return Boolean(value?.isValid() && value.valueOf() > this.parent.startsAt?.valueOf());
      }),
    capacity: Yup.number()
      .typeError('Capacity is required')
      .integer('Use a whole number')
      .min(
        Math.max(1, bookedCount),
        bookedCount
          ? `Capacity cannot be below ${bookedCount} existing bookings`
          : 'Capacity must be at least 1'
      )
      .max(10000, 'Capacity cannot exceed 10,000')
      .required()
      .test('room-capacity', 'Capacity cannot exceed the room capacity', function valid(value) {
        const room = rooms.find((r) => r.id === this.parent.roomId);
        return this.parent.sessionType === 'individualInterview' || !room || value <= room.capacity;
      })
      .test('slots', 'Capacity cannot exceed the available interview slots', function valid(value) {
        return (
          this.parent.sessionType !== 'individualInterview' ||
          value <= sessionSlotCount(this.parent)
        );
      }),
    slotDurationMinutes: Yup.number().when('sessionType', {
      is: 'individualInterview',
      then: (schema) =>
        schema
          .typeError('Slot duration is required')
          .integer('Use a whole number')
          .min(5, 'Duration must be at least 5 minutes')
          .max(180, 'Duration cannot exceed 180 minutes')
          .required(),
    }),
    breakMinutes: Yup.number().when('sessionType', {
      is: 'individualInterview',
      then: (schema) =>
        schema
          .typeError('Gap is required')
          .integer('Use a whole number')
          .min(0, 'Gap cannot be negative')
          .max(60, 'Gap cannot exceed 60 minutes')
          .required(),
    }),
    bookings: Yup.array().test(
      'capacity',
      'Selection exceeds the available seats or slots',
      function valid(value) {
        return !review || (value?.length ?? 0) <= Math.min(this.parent.capacity, 200);
      }
    ),
  });
}

export function sessionSlotCount(
  values: Pick<SessionSetupValues, 'startsAt' | 'endsAt' | 'slotDurationMinutes' | 'breakMinutes'>
) {
  const duration = Number(values.slotDurationMinutes);
  const gap = Number(values.breakMinutes);
  const minutes = ((values.endsAt?.valueOf() ?? 0) - (values.startsAt?.valueOf() ?? 0)) / 60000;
  return duration > 0 && gap >= 0 && minutes >= duration
    ? Math.floor((minutes + gap) / (duration + gap))
    : 0;
}

export function serializeSessionSetup(
  values: SessionSetupValues,
  rooms: SessionRoomChoice[],
  stamp?: string
): SharedSessionInput {
  const room = rooms.find((r) => r.id === values.roomId);
  return {
    name: values.name.trim(),
    scopes: values.offeringIds.map((id) => ({
      admissionOfferingId: id,
      workflowStageDefinitionId: values.stageIds[id],
    })),
    sessionType: values.sessionType,
    roomId: values.roomId,
    location: room
      ? [room.buildingName, room.floorName, room.roomName].filter(Boolean).join(' / ')
      : '',
    interviewerId: values.sessionType !== 'exam' ? values.interviewerId : undefined,
    startsAt: values.startsAt!.toISOString(),
    endsAt: values.endsAt!.toISOString(),
    capacity: Number(values.capacity),
    ...(values.sessionType === 'individualInterview'
      ? {
          slotDurationMinutes: Number(values.slotDurationMinutes),
          breakMinutes: Number(values.breakMinutes),
        }
      : {}),
    concurrencyStamp: stamp,
  };
}

export function selectedSessionStages(
  offeringIds: string[],
  previous: Record<string, string>,
  scopes: AssessmentScope[]
) {
  return Object.fromEntries(
    offeringIds.map((id) => {
      const options = scopes.filter((s) => s.admissionOfferingId === id);
      return [
        id,
        options.some((s) => s.workflowStageDefinitionId === previous[id])
          ? previous[id]
          : options.length === 1
            ? options[0].workflowStageDefinitionId
            : '',
      ];
    })
  );
}

export function assignPreviewSlots(
  items: SessionBookingCandidate[],
  preview: SessionBookingPreview
): SessionBookingCandidate[] {
  return items.map((item) => {
    const suggested = preview.proposedBookings.find(
      (candidate) =>
        candidate.applicationId === item.applicationId &&
        candidate.stageInstanceId === item.stageInstanceId
    );
    return {
      ...item,
      slotStartsAt: suggested?.slotStartsAt ?? null,
      slotEndsAt: suggested?.slotEndsAt ?? null,
    };
  });
}

export function suggestedSessionName(values: SessionSetupValues, scopes: AssessmentScope[]) {
  const type =
    values.sessionType === 'exam'
      ? 'School exam'
      : values.sessionType === 'individualInterview'
        ? 'Individual interview'
        : 'Group interview';
  const stages = Array.from(
    new Set(
      values.offeringIds
        .map(
          (id) =>
            scopes.find(
              (s) =>
                s.admissionOfferingId === id && s.workflowStageDefinitionId === values.stageIds[id]
            )?.stageName
        )
        .filter(Boolean)
    )
  );
  const date = values.startsAt?.isValid() ? fDate(values.startsAt) : '';
  return [type, stages.join(' / '), date].filter(Boolean).join(' · ').slice(0, 128);
}

export function updateSessionSetupValues(
  values: SessionSetupValues,
  key: keyof SessionSetupValues,
  value: unknown,
  scopes: AssessmentScope[],
  rooms: SessionRoomChoice[],
  bookedCount: number
) {
  const next = { ...values, [key]: value } as SessionSetupValues;
  if (key === 'offeringIds')
    next.stageIds = selectedSessionStages(next.offeringIds, values.stageIds, scopes);
  if (key === 'name') next.nameAutoGenerated = !next.name.trim();
  else if (values.nameAutoGenerated || !values.name.trim())
    next.name = suggestedSessionName(next, scopes);
  if (
    bookedCount === 0 &&
    ['roomId', 'startsAt', 'endsAt', 'slotDurationMinutes', 'breakMinutes', 'sessionType'].includes(
      key
    )
  ) {
    const room = rooms.find((r) => r.id === next.roomId);
    if (room) {
      const previousRoom = rooms.find((r) => r.id === values.roomId);
      const previousMaximum =
        values.sessionType === 'individualInterview'
          ? sessionSlotCount(values)
          : (previousRoom?.capacity ?? 0);
      const nextMaximum =
        next.sessionType === 'individualInterview' ? sessionSlotCount(next) : room.capacity;
      const current = Number(values.capacity);
      next.capacity =
        key === 'roomId' || current <= 0 || current === previousMaximum
          ? nextMaximum
          : Math.min(current, nextMaximum);
    }
  }
  return next;
}

// Class is the visible choice; payloads retain the authorized Offering and pinned workflow stage.
export const sessionClassKey = (scope: AssessmentScope) =>
  scope.standardId || scope.admissionOfferingId;
export const sessionAssessmentKey = (scope: AssessmentScope) =>
  `${scope.admissionOfferingId}:${scope.workflowStageDefinitionId}`;
export function selectSessionClasses(
  values: SessionSetupValues,
  classIds: string[],
  scopes: AssessmentScope[]
) {
  const selected = classIds.flatMap((id) => {
    const matches = scopes.filter((scope) => sessionClassKey(scope) === id);
    const previous = matches.find(
      (scope) =>
        values.offeringIds.includes(scope.admissionOfferingId) &&
        values.stageIds[scope.admissionOfferingId] === scope.workflowStageDefinitionId
    );
    return previous ? [previous] : matches.length === 1 ? matches : [];
  });
  return {
    ...values,
    classIds,
    offeringIds: selected.map((scope) => scope.admissionOfferingId),
    stageIds: Object.fromEntries(
      selected.map((scope) => [scope.admissionOfferingId, scope.workflowStageDefinitionId])
    ),
  };
}
export function selectSessionAssessment(
  values: SessionSetupValues,
  classId: string,
  key: string,
  scopes: AssessmentScope[]
) {
  const match = scopes.find(
    (scope) => sessionClassKey(scope) === classId && sessionAssessmentKey(scope) === key
  );
  const retained = values.offeringIds.filter(
    (id) =>
      !scopes.some(
        (scope) => scope.admissionOfferingId === id && sessionClassKey(scope) === classId
      )
  );
  const offeringIds = match ? [...retained, match.admissionOfferingId] : retained;
  return {
    ...values,
    offeringIds,
    stageIds: Object.fromEntries(
      offeringIds.map((id) => [
        id,
        match?.admissionOfferingId === id ? match.workflowStageDefinitionId : values.stageIds[id],
      ])
    ),
  };
}
