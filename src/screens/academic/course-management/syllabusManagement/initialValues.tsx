import dayjs from 'dayjs';

import type { IChapter } from './type';

export const getChapterInitialValues = (editData?: IChapter | null) => {
  const initialValues = {
    chapterNo: editData?.chapterNumber ?? '',
    chapterName: editData?.chapterName || '',
    description: editData?.description || '',
    startDate: editData?.chapterStartTime ? dayjs(editData.chapterStartTime, 'DD-MM-YYYY') : null,
    endDate: editData?.chapterEndTime ? dayjs(editData.chapterEndTime, 'DD-MM-YYYY') : null,
    documents: editData?.documents || [],
    unitName: editData?.unitName || '',
    termName: editData?.termName || '',
    topic: editData?.topic || '',
    estimatedTeachingDays: editData?.estimatedTeachingDays ?? '',
    estimatedPeriods: editData?.estimatedPeriods ?? '',
    revisionDays: editData?.revisionDays ?? '',
    bufferDays: editData?.bufferDays ?? '',
    difficultyLevel: editData?.difficultyLevel || 'Medium',
    bloomLevel: editData?.bloomLevel || 'Understand',
    tags: editData?.tags || '',
    learningOutcomes: editData?.learningOutcomes || '',
    skillsCovered: editData?.skillsCovered || '',
    prerequisites: editData?.prerequisites || '',
    teachingMethods: editData?.teachingMethods || '',
    classActivities: editData?.classActivities || '',
    completionCriteria: editData?.completionCriteria || '',
    teacherNotes: editData?.teacherNotes || '',
    studentSummary: editData?.studentSummary || '',
    parentSummary: editData?.parentSummary || '',
    referenceLinks: editData?.referenceLinks || '',
    worksheets: editData?.worksheets || '',
    audioVideoMaterials: editData?.audioVideoMaterials || '',
    boardDocuments: editData?.boardDocuments || '',
    assessmentMethod: editData?.assessmentMethod || '',
    questionTypes: editData?.questionTypes || '',
    marksWeightage: editData?.marksWeightage ?? '',
    bloomCoverage: editData?.bloomCoverage || '',
    difficultyDistribution: editData?.difficultyDistribution || '',
    visibility: editData?.visibility || 'Teacher',
    publishStatus: editData?.publishStatus || 'Draft',
    reviewStatus: editData?.reviewStatus || 'Not Submitted',
    notifyOnPublish: Boolean(editData?.notifyOnPublish),
    progressPercentage: editData?.progressPercentage ?? 0,
    coverageStatus: editData?.coverageStatus || 'Not Started',
    lessonPlanStatus: editData?.lessonPlanStatus || 'Not Linked',
    homeworkStatus: editData?.homeworkStatus || 'Not Mapped',
    assessmentStatus: editData?.assessmentStatus || 'Not Mapped',
    resourceStatus: editData?.resourceStatus || 'Missing',
    questionCount: editData?.questionCount ?? 0,
    healthScore: editData?.healthScore ?? 0,
    isAiGenerated: Boolean(editData?.isAiGenerated),
    copiedFromPreviousYear: Boolean(editData?.copiedFromPreviousYear),
    templateSource: editData?.templateSource || '',
    dependencyChapterIds: editData?.dependencyChapterIds || '',
    versionLabel: editData?.versionLabel || 'v1',
  };
  return initialValues;
};
