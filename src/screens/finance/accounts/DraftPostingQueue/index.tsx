'use client';

import type { RootState } from 'src/redux/store';
import type { IColumn } from 'src/components/customizabaleTable/types';

import { LoadingButton } from '@mui/lab';
import { useSelector } from 'react-redux';
import { Box, Chip, Typography } from '@mui/material';
import { shikshaMitraToast } from 'src/components/toast';
import React, { useMemo, useState, useCallback } from 'react';
import CustomizableTable from 'src/components/customizabaleTable';
import useQueryAndMutation from 'src/redux/customQueryAndMutation';
import { CustomBreadcrumbs } from 'src/components/custom-breadcrumbs';
import {
  useBulkFinaliseMutation,
  useGetDraftPostingsQuery,
  useFinalisePostingMutation,
} from 'src/redux/finance/accountPostingApi';

const DraftPostingQueue: React.FC = () => {
  const { currentYear } = useSelector((state: RootState) => state.globalState);

  const [queryParams, setQueryParams] = useState({ page: 1, pageSize: 10, search: '' });
  const [selectedIds, setSelectedIds] = useState<string[]>([]);

  const { data: draftData, isLoading } = useQueryAndMutation({
    type: 'query',
    currentQueryAndMutation: useGetDraftPostingsQuery,
    params: { academicYearId: currentYear?.id, ...queryParams },
  });

  const [finalisePosting, { isLoading: isFinalising }] = useQueryAndMutation({
    type: 'mutation',
    currentQueryAndMutation: useFinalisePostingMutation,
  });

  const [bulkFinalise, { isLoading: isBulkFinalising }] = useQueryAndMutation({
    type: 'mutation',
    currentQueryAndMutation: useBulkFinaliseMutation,
  });

  const handleFinalise = useCallback(
    async (id: string) => {
      try {
        await finalisePosting(id).unwrap();
        shikshaMitraToast.success({ message: 'Posting finalised successfully' });
      } catch (error) {
        shikshaMitraToast.error({ message: 'Failed to finalise posting' });
      }
    },
    [finalisePosting]
  );

  const handleBulkFinalise = async () => {
    if (!selectedIds.length) return;
    try {
      await bulkFinalise({ ids: selectedIds }).unwrap();
      shikshaMitraToast.success({
        message: `${selectedIds.length} postings finalised successfully`,
      });
      setSelectedIds([]);
    } catch (error) {
      shikshaMitraToast.error({ message: 'Failed to finalise selected postings' });
    }
  };

  const columns: IColumn[] = useMemo(
    () => [
      {
        id: 'postingDate',
        label: 'Date',
        minWidth: 120,
        render: (value) => (
          <Typography variant="caption" fontSize="13px">
            {value ? new Date(value as string).toLocaleDateString() : '-'}
          </Typography>
        ),
      },
      {
        id: 'eventType',
        label: 'Event Type',
        minWidth: 150,
        render: (value) => (
          <Chip label={(value as string) || '-'} size="small" variant="outlined" />
        ),
      },
      {
        id: 'headAId',
        label: 'Gaining Head',
        minWidth: 150,
        render: (value) => (
          <Typography variant="caption" fontSize="13px">
            {value}
          </Typography>
        ),
      },
      {
        id: 'headBId',
        label: 'Giving Head',
        minWidth: 150,
        render: (value) => (
          <Typography variant="caption" fontSize="13px">
            {value}
          </Typography>
        ),
      },
      {
        id: 'amount',
        label: 'Amount',
        minWidth: 120,
        align: 'left',
        render: (value) => (
          <Typography variant="caption" fontSize="13px" fontWeight={600}>
            ₹{Number(value || 0).toLocaleString('en-IN')}
          </Typography>
        ),
      },
      {
        id: 'sourceModule',
        label: 'Source',
        minWidth: 130,
        render: (value) => (
          <Typography variant="caption" fontSize="13px">
            {value}
          </Typography>
        ),
      },
      {
        id: 'action',
        label: 'Action',
        minWidth: 100,
        render: (value, row) => (
          <LoadingButton
            size="small"
            variant="contained"
            loading={isFinalising}
            onClick={() => handleFinalise((row as any).id)}
          >
            Finalise
          </LoadingButton>
        ),
      },
    ],
    [handleFinalise, isFinalising]
  );

  return (
    <Box height="100%" display="flex" flexDirection="column">
      <CustomBreadcrumbs
        heading="Draft Posting Queue"
        description="Review and finalise draft accounting entries generated by automated finance events."
        links={[
          { name: 'Finance', href: '/finance/dashboard' },
          { name: 'Accounts' },
          { name: 'Draft Postings' },
        ]}
        action={
          <LoadingButton
            variant="contained"
            color="primary"
            disabled={selectedIds.length === 0}
            loading={isBulkFinalising}
            onClick={handleBulkFinalise}
          >
            Finalise Selected ({selectedIds.length})
          </LoadingButton>
        }
        sx={{ px: 1 }}
      />
      <CustomizableTable
        tableId="draft-posting-queue-table"
        columns={columns}
        data={draftData?.items || []}
        isLoading={isLoading}
        serverSidePagination
        serverSideSearch
        totalCount={draftData?.totalCount}
        onServerPagination={(page, rowsPerPage) =>
          setQueryParams((p) => ({ ...p, page, pageSize: rowsPerPage }))
        }
        onServerSearch={(search) => setQueryParams((p) => ({ ...p, search, page: 1 }))}
      />
    </Box>
  );
};

export default DraftPostingQueue;
