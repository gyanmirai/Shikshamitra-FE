export type LibraryPaginatedList<T> = T[] & {
  items: T[];
  totalCount: number;
  currentPage: number;
  pageSize: number;
  totalPages: number;
  total: number;
};

const toStringValue = (value: unknown, fallback = '') =>
  value === null || value === undefined ? fallback : String(value);

const toNumberValue = (value: unknown, fallback = 0) => {
  const numberValue = Number(value);
  return Number.isFinite(numberValue) ? numberValue : fallback;
};

const toArrayValue = <T = any>(value: unknown): T[] => (Array.isArray(value) ? value : []);

export function toLibraryPaginatedList<T>(
  response: any,
  mapItem: (item: any, index: number) => T = (item) => item as T
): LibraryPaginatedList<T> {
  const sourceItems = Array.isArray(response) ? response : response?.items || [];
  const items = sourceItems.map(mapItem);
  const list = items as LibraryPaginatedList<T>;

  list.items = [...items];
  list.totalCount = toNumberValue(
    response?.totalCount ?? response?.total ?? response?.totalItems,
    items.length
  );
  list.currentPage = toNumberValue(response?.currentPage ?? response?.page, 1);
  list.pageSize = toNumberValue(response?.pageSize, items.length);
  list.totalPages = toNumberValue(
    response?.totalPages,
    list.pageSize ? Math.ceil(list.totalCount / list.pageSize) : 1
  );
  list.total = list.totalCount;

  return list;
}

export function mapBookCopyStatus(status: unknown): LibraryBookStatus {
  if (typeof status === 'string') {
    const key = status.replace(/\s+/g, '').toLowerCase();
    const byName: Record<string, LibraryBookStatus> = {
      available: LibraryBookStatus.Available,
      issued: LibraryBookStatus.Issued,
      reserved: LibraryBookStatus.Reserved,
      lost: LibraryBookStatus.Lost,
      damaged: LibraryBookStatus.Damaged,
      underrepair: LibraryBookStatus.UnderMaintenance,
      undermaintenance: LibraryBookStatus.UnderMaintenance,
      discarded: LibraryBookStatus.Removed,
      removed: LibraryBookStatus.Removed,
    };
    return byName[key] ?? LibraryBookStatus.Available;
  }

  const byBackendValue: Record<number, LibraryBookStatus> = {
    0: LibraryBookStatus.Available,
    1: LibraryBookStatus.Issued,
    2: LibraryBookStatus.Reserved,
    3: LibraryBookStatus.Lost,
    4: LibraryBookStatus.Damaged,
    5: LibraryBookStatus.UnderMaintenance,
    6: LibraryBookStatus.Removed,
  };

  return byBackendValue[toNumberValue(status)] ?? LibraryBookStatus.Available;
}

export function mapIssueStatus(status: unknown): LibraryBookStatus {
  const byBackendValue: Record<number, LibraryBookStatus> = {
    0: LibraryBookStatus.Issued,
    1: LibraryBookStatus.Returned,
    2: LibraryBookStatus.Overdue,
  };

  return byBackendValue[toNumberValue(status)] ?? LibraryBookStatus.Issued;
}

