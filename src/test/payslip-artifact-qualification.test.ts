// @vitest-environment node
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import { it, expect, describe } from 'vitest';

import { extractPayslipPdfText } from '../screens/hr/payroll/salarySlip-generate/payslip-pdf-text';

// Resolve the installed Node20-compatible module without loading the browser build.
const loadPdfJs = (): Promise<typeof import('pdfjs-dist')> => import(/* @vite-ignore */ pathToFileURL(
  createRequire(import.meta.url).resolve('pdfjs-dist/legacy/build/pdf.mjs')
).href);

// Generated by the authenticated, capture-only backend payroll matrix and facts-correction tests.
// No substitute document, inferred salary calculation or mocked PDF renderer is used here.
type ArtifactFacts = {
  employeeName: string; employeeCode: string; department: string | null; designation: string | null;
  bankName: string | null; maskedAccountNumber: string | null; ifscCode: string | null;
  uanNumber: string | null; epfNumber: string | null; employeeStateInsuranceNumber: string | null;
  slipNumber: string; generatedAt: string; lopDays: number; fullGrossSalary: number;
  totalEarning: number; totalDeduction: number; netPay: number;
  earnings: { name: string; amount: number }[]; deductions: { name: string; amount: number }[];
};

const root = process.env.PAYSLIP_PDF_ARTIFACT_DIRECTORY ?? '';
const scenarios = ['gross', 'ctc', 'partial', 'joining', 'zero', 'additional', 'exempt',
  'noncovered', 'leaving', 'overtime', 'relief', 'unicode', 'off', 'off-bank', 'paid-original',
  'paid-corrected', 'unpaid-original', 'unpaid-corrected'];
const money = (value: number) => value.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const nonblank = (value: string | null) => Boolean(value?.trim());

describe.skipIf(!root)('Canonical issued payslip artifacts', () => {
  it.each(scenarios)('%s preserves issued fields and omits empty sections', async (scenario) => {
    const pdfjs = await loadPdfJs();
    expect(pdfjs.version).toBe('5.6.205');
    const facts: ArtifactFacts = JSON.parse(await readFile(path.join(root, `${scenario}.json`), 'utf8'));
    const bytes = await readFile(path.join(root, `${scenario}.pdf`));
    expect(bytes.subarray(0, 5).toString('ascii')).toBe('%PDF-');
    const loading = pdfjs.getDocument({ data: new Uint8Array(bytes), useSystemFonts: true });
    const document = await loading.promise;
    try {
      expect(document.numPages).toBe(1);
      const page = await document.getPage(1);
      const viewport = page.getViewport({ scale: 1 });
      expect(viewport.width).toBeCloseTo(595.28, 0);
      expect(viewport.height).toBeCloseTo(841.89, 0);
      const content = await page.getTextContent({ includeMarkedContent: true });
      const text = extractPayslipPdfText(content, await page.getStructTree()).replace(/\s+/g, ' ');
      const glyphs = text.replace(/\s+/g, '');
      expect(text.includes('\u0000')).toBe(false);
      expect(text.includes('\ufffd')).toBe(false);
      [facts.employeeName, facts.employeeCode, facts.department, facts.designation, facts.bankName, facts.maskedAccountNumber, facts.ifscCode, facts.uanNumber, facts.epfNumber, facts.employeeStateInsuranceNumber].forEach((field) => {
        if (field) expect(glyphs).toContain(field.replace(/\s+/g, ''));
      });
      expect(text).toContain(facts.slipNumber);
      const date = new Intl.DateTimeFormat('en-GB', { timeZone: 'Asia/Kolkata', day: '2-digit', month: 'short', year: 'numeric' }).format(new Date(facts.generatedAt));
      expect(text).toContain(`Generated On: ${date}`);
      expect(text).toContain(`Non-payable days: ${facts.lopDays}`);
      [facts.totalEarning, facts.totalDeduction, facts.netPay, facts.fullGrossSalary].forEach((amount) => expect(text).toContain(`Rs. ${money(amount)}`));
      [...facts.earnings, ...facts.deductions].forEach((line) => {
        expect(text).toContain(line.name === 'Employee State Insurance (ESI) - Auto' ? 'Employee ESI' : line.name);
        expect(text).toContain(`Rs. ${money(line.amount)}`);
      });
      expect(text).not.toMatch(/Employer ESI|Employer contribution|\bCTC\b|PROTECT_EMPLOYER_COST| - Auto\b/i);
      const bank = [facts.bankName, facts.maskedAccountNumber, facts.ifscCode].some(nonblank);
      const statutory = [facts.uanNumber, facts.epfNumber, facts.employeeStateInsuranceNumber].some(nonblank);
      if (bank && statutory) expect(text).toContain('Payment & Statutory');
      else if (bank) expect(text).toContain('Payment details');
      else if (statutory) expect(text).toContain('Statutory details');
      else expect(text).not.toMatch(/Payment & Statutory|Payment details|Statutory details/);
      if (scenario === 'off' || scenario === 'off-bank') expect(text).not.toMatch(/Employee ESI|ESIC insurance number|Statutory/);
      if (scenario === 'exempt' || scenario === 'noncovered') expect(text).not.toContain('Employee ESI');
    } finally { await loading.destroy(); }
  });
});
